def _clean(value):
    return re.sub(r"\s+", " ", value or "").strip()


def build_response(want):
    name = _clean(want.get("name") or "заказ")
    desc = _clean(want.get("description") or "")
    category_id = str(want.get("category_id") or "")
    category = NAME_BY_ID.get(category_id, "вашей категории")

    pitch = _CATEGORY_PITCH.get(category_id, "У меня есть опыт в этой области: "
                                             "аккуратно выполняю работу, держу сроки и всегда на связи.")

    extra = []
    for key, text in _GOODS.items():
        if key in desc.lower() or key in name.lower():
            extra.append(text)
    for key, text in _KEYWORDS.items():
        if key in desc.lower():
            extra.append(text)

    lines = ["Здравствуйте!"]
    hint = _clean(desc[:140])
    if hint:
        lines.append(f"Изучил вашу задачу: {hint}…")
    lines.append(f"Уверен, что справлюсь — {pitch}")
    lines.extend(extra[:2])
    lines.append("Скажите удобное время — созвонимся или продолжим в переписке, уточню детали и назову точный срок и цену.")
    if ABOUT:
        lines.append(ABOUT)
    lines.append(SIGNATURE)

    return "\n\n".join(lines)


def want_to_text(want):
    category_id = str(want.get("category_id") or "")
    category = NAME_BY_ID.get(category_id, "—")
    price = want.get("priceLimit") or "—"
    budget = f"{price} ₽" if price != "—" else "не указан"
    time_left = want.get("timeLeft") or "—"
    name = html.escape(_clean(want.get("name") or "Заказ"))
    desc = html.escape(_clean(want.get("description") or ""))

    text = (
        f"📌 <b>{name}</b>\n"
        f"🏷 {category}  ·  💰 {budget}  ·  ⏳ {time_left}\n\n"
    )
    if desc:
        text += f"📝 {desc}\n\n"
    return text
